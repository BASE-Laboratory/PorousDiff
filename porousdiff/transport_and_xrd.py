def write_openimpala_ini(
    ini_path: Path,
    tiff_path: Path,
    output_prefix: Path,
    transport_phase: str = "pore",
    phase_value: int = 0,
    directions: tuple[str, ...] = ("z", "x", "y"),
    phase_conductivities: str | None = None,
    template_ini: Path | None = None,
) -> Path:
    """Write an OpenImpala `TortuosityFD` INI configuration file (or substitute a user template)."""
    ini_path.parent.mkdir(parents=True, exist_ok=True)
    output_prefix.parent.mkdir(parents=True, exist_ok=True)
    dirs_str = ",".join(directions)

    if template_ini is not None:
        raw_tpl = template_ini.read_text()
        content = raw_tpl.format(
            tiff_path=str(tiff_path.resolve()),
            phase=int(phase_value),
            transport_phase=transport_phase,
            output_prefix=str(output_prefix.resolve()),
            directions=dirs_str,
            phase_conductivities=phase_conductivities or "",
        )
        ini_path.write_text(content)
        return ini_path

    geom_lines = [
        "# Auto-generated by PorousDiff v0.4 for OpenImpala TortuosityFD",
        "[Geometry]",
        f"filename = {tiff_path.resolve()}",
        f"phase = {int(phase_value)}",
        f"label = {transport_phase}",
    ]
    if phase_conductivities:
        geom_lines.append(f"phase_conductivities = {phase_conductivities}")

    content = "\n".join(
        [
            *geom_lines,
            "",
            "[Solver]",
            "solver_type = DiffusionFD",
            f"directions = {dirs_str}",
            "tolerance = 1e-6",
            "max_iterations = 20000",
            "",
            "[Output]",
            f"output_prefix = {output_prefix.resolve()}",
            "write_json = true",
            "",
        ]
    )
    ini_path.write_text(content)
    return ini_path


def generate_openimpala_job_suite(
    tiff_entries: Iterable[Mapping[str, object]],
    suite_dir: Path,
    openimpala_cmd: str = "openimpala",
    template_ini: Path | None = None,
    include_hetero_solid: bool = False,
    hetero_conductivities: str = "1:1.0,2:0.01",
) -> dict[str, object]:
    """Generate INI configs, `openimpala_jobs.json`, and `run_openimpala_batch.sh` across methods.

    Each item in `tiff_entries` should contain:
      - `method`: e.g. `"real"`, `"affine_z_squash"`, `"pillar_pore_deletion"`, `"porousdiff"`
      - `state`: state identifier
      - `material`: material key
      - `beamline`: beamline identifier
      - `load_value`: scalar load or stress
      - `tiff_path`: `Path` to exported 3D multi-page `.tif` (`0=pore`, `1=carbon`, `2=coating`)
      - `num_phases`: `2` or `3`
    """
    suite_dir.mkdir(parents=True, exist_ok=True)
    cfg_dir = suite_dir / "configs"
    out_dir = suite_dir / "outputs"
    cfg_dir.mkdir(parents=True, exist_ok=True)
    out_dir.mkdir(parents=True, exist_ok=True)

    jobs: list[dict[str, object]] = []
    shell_lines = [
        "#!/bin/bash",
        "set -euo pipefail",
        f'OPENIMPALA_BIN="${{OPENIMPALA_BIN:-{openimpala_cmd}}}"',
        "",
    ]

    for entry in tiff_entries:
        method = str(entry["method"])
        state = str(entry["state"])
        material = str(entry.get("material", "virgin_carbon"))
        beamline = str(entry.get("beamline", "primary"))
        load_val = float(entry.get("load_value", 0.0))  # type: ignore[arg-type]
        tiff_path = Path(str(entry["tiff_path"]))
        n_ph = int(entry.get("num_phases", 2))  # type: ignore[arg-type]
        stem = tiff_path.stem

        # Configure ionic pore-phase diffusion (phase 0) and carbon backbone (phase 1);
        # for 3-phase coated electrodes also configure active coating (phase 2) and optional
        # heterogeneous composite solid conduction (`1:1.0,2:0.01`).
        phase_targets: list[tuple[str, int, str | None]] = [
            ("pore_ionic", 0, None),
            ("carbon_electronic", 1, None),
        ]
        if n_ph == 3:
            phase_targets.append(("coating_active", 2, None))
            if include_hetero_solid:
                phase_targets.append(("solid_hetero_electronic", 1, hetero_conductivities))

        for transport_name, ph_val, ph_cond in phase_targets:
            job_id = f"{method}__{state}__{stem}__{transport_name}"
            ini_path = cfg_dir / f"{job_id}.ini"
            out_prefix = out_dir / job_id
            write_openimpala_ini(
                ini_path=ini_path,
                tiff_path=tiff_path,
                output_prefix=out_prefix,
                transport_phase=transport_name,
                phase_value=ph_val,
                phase_conductivities=ph_cond,
                template_ini=template_ini,
            )
            jobs.append(
                {
                    "job_id": job_id,
                    "method": method,
                    "state": state,
                    "material": material,
                    "beamline": beamline,
                    "load_value": load_val,
                    "transport_phase": transport_name,
                    "phase_value": ph_val,
                    "phase_conductivities": ph_cond,
                    "tiff_path": str(tiff_path.resolve()),
                    "ini_path": str(ini_path.resolve()),
                    "output_json": str((out_dir / f"{job_id}.json").resolve()),
                }
            )
            shell_lines.append(f'"$OPENIMPALA_BIN" "{ini_path.resolve()}"')

    manifest = {"num_jobs": len(jobs), "jobs": jobs}
    manifest_path = suite_dir / "openimpala_jobs.json"
    manifest_path.write_text(json.dumps(manifest, indent=2))

    script_path = suite_dir / "run_openimpala_batch.sh"
    script_path.write_text("\n".join(shell_lines) + "\n")
    script_path.chmod(0o755)
    return {
        "suite_dir": str(suite_dir),
        "manifest_path": str(manifest_path),
        "script_path": str(script_path),
        "num_jobs": len(jobs),
    }


def _parse_single_openimpala_file(path: Path) -> dict[str, float]:
    """Extract `d_eff_x/y/z`, `tau_x/y/z`, and `volume_fraction` from JSON or key-value log."""
    if path.suffix.lower() == ".json":
        raw = json.loads(path.read_text())
        out: dict[str, float] = {}
        for k, v in raw.items():
            if isinstance(v, (int, float)):
                out[k.lower()] = float(v)
            elif isinstance(v, dict):
                for sk, sv in v.items():
                    if isinstance(sv, (int, float)):
                        out[f"{k.lower()}_{sk.lower()}"] = float(sv)
        return out

    text = path.read_text(errors="replace")
    parsed: dict[str, float] = {}
    for m in re.finditer(
        r"(d_eff_[xyz]|deff_[xyz]|tortuosity_[xyz]|tau_[xyz]|volume_fraction|porosity)\s*[:=]\s*([0-9.eE+-]+)",
        text,
        flags=re.IGNORECASE,
    ):
        key = m.group(1).lower().replace("deff_", "d_eff_").replace("tortuosity_", "tau_")
        parsed[key] = float(m.group(2))
    return parsed


def parse_openimpala_results(
    suite_dir: Path,
    out_csv: Path | None = None,
) -> list[dict[str, object]]:
    """Ingest completed OpenImpala outputs matched against `openimpala_jobs.json`."""
    jobs_file = suite_dir / "openimpala_jobs.json"
    if not jobs_file.is_file():
        raise FileNotFoundError(f"Missing OpenImpala job manifest: {jobs_file}")

    jobs = json.loads(jobs_file.read_text()).get("jobs", [])
    rows: list[dict[str, object]] = []
    outputs_dir = suite_dir / "outputs"

    for job in jobs:
        job_id = str(job["job_id"])
        candidates = [
            Path(str(job["output_json"])),
            outputs_dir / f"{job_id}.log",
            outputs_dir / f"{job_id}.txt",
        ]
        found = next((p for p in candidates if p.is_file()), None)
        if found is None:
            continue
        metrics = _parse_single_openimpala_file(found)
        row: dict[str, object] = {
            "job_id": job_id,
            "method": job["method"],
            "state": job["state"],
            "material": job["material"],
            "beamline": job["beamline"],
            "load_value": job["load_value"],
            "transport_phase": job["transport_phase"],
        }
        row.update(metrics)
        rows.append(row)

    if out_csv is not None and rows:
        out_csv.parent.mkdir(parents=True, exist_ok=True)
        keys: list[str] = []
        for r in rows:
            for k in r:
                if k not in keys:
                    keys.append(k)
        with out_csv.open("w", newline="") as f:
            writer = csv.DictWriter(f, fieldnames=keys)
            writer.writeheader()
            writer.writerows(rows)
    return rows


def has_openimpala_python() -> bool:
    """Return True if the `openimpala` v4.6+ Python facade is installed in the current environment."""
    return importlib.util.find_spec("openimpala") is not None


def _solve_openimpala_phase_transport(
    volume: np.ndarray,
    phase: int,
    voxel_size_um: float = 1.0,
    phase_diffusivities: Mapping[int, float] | None = None,
    compute_homogenized_tensor: bool = False,
) -> dict[str, float]:
    """Solve directional steady-state PDE transport (and optional 3x3 homogenization) via OpenImpala."""
    import openimpala as oi

    oi.Session.ensure_active()
    vol = np.asarray(volume, dtype=np.uint8)
    vox = max(float(voxel_size_um), 1e-6)

    if phase_diffusivities is not None:
        active_labels = [int(k) for k, v in phase_diffusivities.items() if float(v) > 0.0]
        vol_frac = float(np.mean(np.isin(vol, active_labels))) if active_labels else 0.0
    else:
        vol_frac = float(np.mean(vol == int(phase)))

    try:
        res_all = oi.tortuosity_all(
            vol,
            phase=int(phase),
            strict=False,
            voxel_size=vox,
            phase_diffusivities=phase_diffusivities,
        )
    except oi.OpenImpalaError:
        res_all = {"x": None, "y": None, "z": None}

    metrics: dict[str, float] = {"volume_fraction": vol_frac}
    conv_flags: list[float] = []
    for axis_name in ("x", "y", "z"):
        r = res_all.get(axis_name)
        if r is None:
            metrics[f"d_eff_{axis_name}"] = 0.0
            metrics[f"tau_{axis_name}"] = float("nan")
            metrics[f"percolates_{axis_name}"] = 0.0
            conv_flags.append(1.0)
        else:
            deff_val = float(r.effective_diffusivity)
            tau_val = float(r.tortuosity)
            metrics[f"d_eff_{axis_name}"] = max(0.0, deff_val) if np.isfinite(deff_val) else 0.0
            metrics[f"tau_{axis_name}"] = tau_val if np.isfinite(tau_val) else float("nan")
            metrics[f"percolates_{axis_name}"] = 1.0
            conv_flags.append(1.0 if bool(r.solver_converged) else 0.0)
    metrics["solver_converged"] = float(min(conv_flags)) if conv_flags else 0.0

    if compute_homogenized_tensor:
        try:
            eff_res = oi.effective_diffusivity(
                vol,
                phase=int(phase),
                voxel_size=vox,
                phase_diffusivities=phase_diffusivities,
            )
            ten = np.asarray(eff_res.tensor, dtype=np.float64)
            metrics["homogenized_d_xx"] = float(max(0.0, ten[0, 0]))
            metrics["homogenized_d_yy"] = float(max(0.0, ten[1, 1]))
            metrics["homogenized_d_zz"] = float(max(0.0, ten[2, 2]))
            metrics["homogenized_d_xy"] = float(ten[0, 1])
            metrics["homogenized_d_xz"] = float(ten[0, 2])
            metrics["homogenized_d_yz"] = float(ten[1, 2])
        except oi.OpenImpalaError:
            metrics["homogenized_d_xx"] = 0.0
            metrics["homogenized_d_yy"] = 0.0
            metrics["homogenized_d_zz"] = 0.0
            metrics["homogenized_d_xy"] = 0.0
            metrics["homogenized_d_xz"] = 0.0
            metrics["homogenized_d_yz"] = 0.0

    return metrics


def compute_openimpala_volume_transport(
    volume: np.ndarray,
    voxel_size_um: float = 1.0,
    num_phases: int | None = None,
    include_hetero_solid: bool = True,
    coating_rel_conductivity: float = 0.05,
    compute_homogenized_tensor: bool = False,
) -> dict[str, object]:
    """Run in-process OpenImpala v4.6 PDE transport & interfacial characterization on a 3D `(Z, Y, X)` volume."""
    import openimpala as oi

    oi.Session.ensure_active()
    vol = np.asarray(volume, dtype=np.uint8)
    if vol.ndim != 3:
        raise ValueError(f"Expected 3D volume (Z, Y, X), got shape {vol.shape}")
    vox = max(float(voxel_size_um), 1e-6)
    n_ph = int(num_phases) if num_phases is not None else (3 if int(np.max(vol)) >= 2 else 2)

    vol_bin = (vol > 0).astype(np.uint8)
    phases_out: dict[str, dict[str, float]] = {}

    phases_out["pore_ionic"] = _solve_openimpala_phase_transport(
        vol if n_ph == 3 else vol_bin,
        phase=0,
        voxel_size_um=vox,
        compute_homogenized_tensor=compute_homogenized_tensor,
    )
    phases_out["carbon_electronic"] = _solve_openimpala_phase_transport(
        vol if n_ph == 3 else vol_bin,
        phase=1,
        voxel_size_um=vox,
        compute_homogenized_tensor=compute_homogenized_tensor,
    )
    if n_ph == 3:
        phases_out["coating_active"] = _solve_openimpala_phase_transport(
            vol,
            phase=2,
            voxel_size_um=vox,
            compute_homogenized_tensor=compute_homogenized_tensor,
        )
        if include_hetero_solid:
            phases_out["solid_hetero_electronic"] = _solve_openimpala_phase_transport(
                vol,
                phase=1,
                voxel_size_um=vox,
                phase_diffusivities={0: 0.0, 1: 1.0, 2: float(coating_rel_conductivity)},
                compute_homogenized_tensor=compute_homogenized_tensor,
            )

    ssa_bin = oi.specific_surface_area(vol_bin, phase_a=0, phase_b=1, voxel_size=vox)
    interfacial: dict[str, float] = {
        "ssa_total_raw": float(ssa_bin.ssa),
        "ssa_total_cc": float(ssa_bin.ssa_corrected),
    }
    if n_ph == 3:
        ssa_pc = oi.specific_surface_area(vol, phase_a=0, phase_b=2, voxel_size=vox)
        ssa_pcarb = oi.specific_surface_area(vol, phase_a=0, phase_b=1, voxel_size=vox)
        ssa_cc = oi.specific_surface_area(vol, phase_a=1, phase_b=2, voxel_size=vox)
        interfacial.update(
            {
                "ssa_pore_coating_raw": float(ssa_pc.ssa),
                "ssa_pore_coating_cc": float(ssa_pc.ssa_corrected),
                "ssa_pore_carbon_raw": float(ssa_pcarb.ssa),
                "ssa_pore_carbon_cc": float(ssa_pcarb.ssa_corrected),
                "ssa_carbon_coating_raw": float(ssa_cc.ssa),
                "ssa_carbon_coating_cc": float(ssa_cc.ssa_corrected),
            }
        )

    prof_z = oi.through_thickness_profile(vol_bin, phase=1, direction="z", voxel_size=vox)
    prof_arr = np.asarray(prof_z.profile, dtype=np.float64)

    lookup_summary: dict[str, float] = {
        "pore_d_eff_z": float(phases_out["pore_ionic"]["d_eff_z"]),
        "solid_sigma_eff_z": float(phases_out["carbon_electronic"]["d_eff_z"]),
    }
    if "solid_hetero_electronic" in phases_out:
        lookup_summary["solid_hetero_sigma_eff_z"] = float(
            phases_out["solid_hetero_electronic"]["d_eff_z"]
        )

    return {
        "num_phases": n_ph,
        "voxel_size_um": vox,
        "phases": phases_out,
        "interfacial": interfacial,
        "through_thickness_solid_z": {
            "mean": float(np.mean(prof_arr)),
            "std": float(np.std(prof_arr)),
            "min": float(np.min(prof_arr)),
            "max": float(np.max(prof_arr)),
        },
        "lookup_summary": lookup_summary,
    }


def run_openimpala_python_suite(
    tiff_entries: Iterable[Mapping[str, object]],
    suite_dir: Path,
    out_csv: Path | None = None,
    include_hetero_solid: bool = True,
    coating_rel_conductivity: float = 0.05,
    compute_homogenized_tensor: bool = False,
) -> list[dict[str, object]]:
    """Execute OpenImpala v4.6 PDE transport directly in-process across Real, Baselines & PorousDiff.

    Writes per-job JSON artifacts under `suite_dir / 'outputs'`, `openimpala_jobs.json`, and
    `out_csv` (`openimpala_transport_parity.csv`) directly consumable by `load_openimpala_lookup`.
    """
    suite_dir = Path(suite_dir)
    outputs_dir = suite_dir / "outputs"
    outputs_dir.mkdir(parents=True, exist_ok=True)

    jobs: list[dict[str, object]] = []
    rows: list[dict[str, object]] = []

    for idx, entry in enumerate(tiff_entries, start=1):
        method = str(entry["method"])
        state = str(entry["state"])
        material = str(entry.get("material", "virgin_carbon"))
        beamline = str(entry.get("beamline", "primary"))
        load_val = float(entry.get("load_value", 0.0))  # type: ignore[arg-type]
        n_ph = int(entry.get("num_phases", 2))  # type: ignore[arg-type]
        vox = float(entry.get("voxel_size_um", 1.0))  # type: ignore[arg-type]

        if "volume" in entry and entry["volume"] is not None:
            vol = np.asarray(entry["volume"], dtype=np.uint8)
            stem = str(entry.get("stem", f"vol_{idx:03d}"))
            tiff_str = str(entry.get("tiff_path", ""))
        else:
            tiff_path = Path(str(entry["tiff_path"]))
            vol = np.asarray(tifffile.imread(tiff_path), dtype=np.uint8)
            stem = tiff_path.stem
            tiff_str = str(tiff_path.resolve())

        vol_res = compute_openimpala_volume_transport(
            vol,
            voxel_size_um=vox,
            num_phases=n_ph,
            include_hetero_solid=include_hetero_solid,
            coating_rel_conductivity=coating_rel_conductivity,
            compute_homogenized_tensor=compute_homogenized_tensor,
        )
        phases_map: dict[str, dict[str, float]] = vol_res["phases"]  # type: ignore[assignment]
        for transport_name, p_metrics in phases_map.items():
            job_id = f"{method}__{state}__{stem}__{transport_name}"
            out_json = outputs_dir / f"{job_id}.json"
            out_json.write_text(json.dumps(p_metrics, indent=2))
            jobs.append(
                {
                    "job_id": job_id,
                    "method": method,
                    "state": state,
                    "material": material,
                    "beamline": beamline,
                    "load_value": load_val,
                    "transport_phase": transport_name,
                    "tiff_path": tiff_str,
                    "output_json": str(out_json.resolve()),
                }
            )
            row: dict[str, object] = {
                "job_id": job_id,
                "method": method,
                "state": state,
                "material": material,
                "beamline": beamline,
                "load_value": load_val,
                "transport_phase": transport_name,
            }
            row.update(p_metrics)
            rows.append(row)

    (suite_dir / "openimpala_jobs.json").write_text(
        json.dumps({"num_jobs": len(jobs), "jobs": jobs, "executed_in_process": True}, indent=2)
    )

    if out_csv is not None and rows:
        out_csv = Path(out_csv)
        out_csv.parent.mkdir(parents=True, exist_ok=True)
        fieldnames: list[str] = []
        for r in rows:
            for k in r:
                if k not in fieldnames:
                    fieldnames.append(k)
        with out_csv.open("w", newline="") as f:
            writer = csv.DictWriter(f, fieldnames=fieldnames)
            writer.writeheader()
            writer.writerows(rows)
    return rows


def run_openimpala_rev_convergence(
    volume: np.ndarray,
    sizes: Sequence[int] | None = None,
    phase: int = 0,
    num_samples: int = 3,
    voxel_size_um: float = 1.0,
    out_dir: Path | None = None,
    seed: int = 42,
) -> dict[str, object]:
    """Run an OpenImpala Representative Elementary Volume (REV) convergence & Z-uniformity study."""
    import openimpala as oi

    oi.Session.ensure_active()
    vol = np.asarray(volume, dtype=np.uint8)
    if vol.ndim != 3:
        raise ValueError(f"Expected 3D volume (Z, Y, X), got shape {vol.shape}")
    min_dim = int(min(vol.shape))
    vox = max(float(voxel_size_um), 1e-6)

    if sizes is None:
        cand_sizes = sorted({max(8, min_dim // 2), max(8, (3 * min_dim) // 4), min_dim})
    else:
        cand_sizes = sorted({int(s) for s in sizes if 4 <= int(s) <= min_dim})
    if not cand_sizes:
        cand_sizes = [min_dim]

    csv_path_str = str((Path(out_dir) / "rev_convergence.csv").resolve()) if out_dir is not None else None
    if out_dir is not None:
        Path(out_dir).mkdir(parents=True, exist_ok=True)

    size_rows: list[dict[str, float]] = []
    try:
        rev_res = oi.rev_study(
            vol,
            sizes=cand_sizes,
            num_samples=max(1, int(num_samples)),
            phase=int(phase),
            voxel_size=vox,
            csv_path=csv_path_str,
        )
        for sz in rev_res.sizes:
            mu = np.asarray(rev_res.mean_diagonal[sz], dtype=np.float64)
            sd = np.asarray(rev_res.std_diagonal[sz], dtype=np.float64)
            cov_zz = float(sd[2] / max(mu[2], 1e-8)) if mu[2] > 1e-8 else 0.0
            size_rows.append(
                {
                    "subvolume_size": float(sz),
                    "mean_d_xx": float(mu[0]),
                    "mean_d_yy": float(mu[1]),
                    "mean_d_zz": float(mu[2]),
                    "std_d_xx": float(sd[0]),
                    "std_d_yy": float(sd[1]),
                    "std_d_zz": float(sd[2]),
                    "cov_d_zz": cov_zz,
                }
            )
    except oi.OpenImpalaError:
        # Graceful fallback when random sub-cubes contain non-percolating throats
        rng = np.random.default_rng(seed)
        d_dim, h_dim, w_dim = vol.shape
        for sz in cand_sizes:
            n_s = 1 if sz == min_dim else max(1, int(num_samples))
            samples_xyz: list[list[float]] = []
            for _ in range(n_s):
                z0 = int(rng.integers(0, d_dim - sz + 1)) if d_dim > sz else 0
                y0 = int(rng.integers(0, h_dim - sz + 1)) if h_dim > sz else 0
                x0 = int(rng.integers(0, w_dim - sz + 1)) if w_dim > sz else 0
                sub = vol[z0 : z0 + sz, y0 : y0 + sz, x0 : x0 + sz]
                pm = _solve_openimpala_phase_transport(sub, phase=int(phase), voxel_size_um=vox)
                samples_xyz.append([pm["d_eff_x"], pm["d_eff_y"], pm["d_eff_z"]])
            arr = np.asarray(samples_xyz, dtype=np.float64)
            mu = arr.mean(axis=0)
            sd = arr.std(axis=0)
            cov_zz = float(sd[2] / max(mu[2], 1e-8)) if mu[2] > 1e-8 else 0.0
            size_rows.append(
                {
                    "subvolume_size": float(sz),
                    "mean_d_xx": float(mu[0]),
                    "mean_d_yy": float(mu[1]),
                    "mean_d_zz": float(mu[2]),
                    "std_d_xx": float(sd[0]),
                    "std_d_yy": float(sd[1]),
                    "std_d_zz": float(sd[2]),
                    "cov_d_zz": cov_zz,
                }
            )
        if out_dir is not None and size_rows:
            with (Path(out_dir) / "rev_convergence.csv").open("w", newline="") as f:
                writer = csv.DictWriter(f, fieldnames=list(size_rows[0].keys()))
                writer.writeheader()
                writer.writerows(size_rows)

    prof = oi.through_thickness_profile(
        (vol > 0).astype(np.uint8), phase=1, direction="z", voxel_size=vox
    )
    prof_arr = np.asarray(prof.profile, dtype=np.float64)
    largest_cov = float(size_rows[-1]["cov_d_zz"]) if size_rows else float("nan")
    summary: dict[str, object] = {
        "volume_shape": list(vol.shape),
        "phase": int(phase),
        "voxel_size_um": vox,
        "largest_subvolume_cov_d_zz": largest_cov,
        "rev_converged_5pct": bool(np.isfinite(largest_cov) and largest_cov <= 0.05),
        "z_solid_profile_mean": float(np.mean(prof_arr)),
        "z_solid_profile_std": float(np.std(prof_arr)),
        "sizes": size_rows,
    }
    if out_dir is not None:
        (Path(out_dir) / "rev_convergence_summary.json").write_text(json.dumps(summary, indent=2))
    return summary


def correlate_xrd_with_microstructure(
    xrd_csv_path: Path,
    benchmark_report: Mapping[str, object],
    out_dir: Path,
    preferred_method: str | None = None,
) -> dict[str, object]:
    """Correlate DLS K11 DIAD co-registered XRD observables with 3D XCT & PorousDiff metrics.

    Expects `xrd_csv_path` to contain a `state` column (matching manifest state names) OR
    (`material` + `load_value`/`stress_kpa`/`load_mv_per_v`), plus one or more numeric XRD
    columns (e.g. `d_spacing_A`, `lattice_strain_pct`, `fwhm_deg`, `coating_peak_ratio`).
    """
    out_dir.mkdir(parents=True, exist_ok=True)
    with xrd_csv_path.open("r", newline="") as f:
        xrd_rows = list(csv.DictReader(f))
    if not xrd_rows:
        raise ValueError(f"XRD CSV {xrd_csv_path} is empty")

    reserved = {
        "state",
        "folder",
        "dataset",
        "material",
        "beamline",
        "load",
        "load_value",
        "stress_kpa",
        "load_mv_per_v",
    }
    xrd_cols = [
        c
        for c in (xrd_rows[0].keys() if xrd_rows else [])
        if c and c.strip().lower() not in reserved
    ]

    micro_keys = [
        "solid_fraction",
        "coating_fraction",
        "ssa_pore_coating",
        "tpb_density",
        "wired_coating_fraction",
        "geodesic_tortuosity_z",
        "geodesic_solid_tortuosity_z",
        "z_pinch_contact_density",
        "specific_z_pinch_excess",
        "coating_pinch_fraction",
        "mean_coating_coordination",
    ]

    merged_rows: list[dict[str, object]] = []
    for xrow in xrd_rows:
        st_match: str | None = None
        raw_st = (xrow.get("state") or xrow.get("folder") or xrow.get("dataset") or "").strip()
        if raw_st and raw_st in benchmark_report:
            st_match = raw_st
        elif raw_st:
            # Allow suffix match when collision-safe prefixes like `DLS_K11_DIAD__...` were added
            for cand_st in benchmark_report:
                if str(cand_st).endswith(raw_st):
                    st_match = str(cand_st)
                    break

        if st_match is None:
            raw_lv = xrow.get("load_value") or xrow.get("stress_kpa") or xrow.get("load_mv_per_v") or xrow.get("load")
            raw_mat = (xrow.get("material") or "").strip()
            if raw_lv is not None and str(raw_lv).strip():
                target_lv = float(str(raw_lv).strip())
                best_st = None
                best_diff = float("inf")
                for cand_st, entry in benchmark_report.items():
                    ent = entry  # type: ignore[assignment]
                    if raw_mat and str(ent.get("material", "")) != raw_mat:  # type: ignore[union-attr]
                        continue
                    diff = abs(float(ent.get("load_value", 0.0)) - target_lv)  # type: ignore[union-attr]
                    if diff < best_diff and diff <= max(1e-4, 0.05 * max(abs(target_lv), 1e-3)):
                        best_diff = diff
                        best_st = str(cand_st)
                st_match = best_st

        if st_match is None:
            continue

        entry = benchmark_report[st_match]  # type: ignore[index]
        methods_dict = entry.get("methods", {})  # type: ignore[union-attr]
        chosen_method = preferred_method
        if chosen_method is None or chosen_method not in methods_dict:
            non_base = [m for m in methods_dict if m not in ("affine_z_squash", "pillar_pore_deletion")]
            chosen_method = non_base[0] if non_base else (next(iter(methods_dict), None))

        merged: dict[str, object] = {
            "state": st_match,
            "material": entry.get("material", ""),  # type: ignore[union-attr]
            "load_value": float(entry.get("load_value", 0.0)),  # type: ignore[union-attr]
            "pred_method": chosen_method or "",
        }
        for xc in xrd_cols:
            try:
                merged[f"xrd_{xc}"] = float(str(xrow[xc]).strip())
            except (TypeError, ValueError):
                merged[f"xrd_{xc}"] = float("nan")

        real_m = entry["real"]["metrics"]  # type: ignore[index]
        for mk in micro_keys:
            if mk in real_m:
                merged[f"real_{mk}"] = float(real_m[mk]["mean"])

        if chosen_method and chosen_method in methods_dict:
            pred_m = methods_dict[chosen_method]["metrics"]
            for mk in micro_keys:
                if mk in pred_m:
                    merged[f"pred_{mk}"] = float(pred_m[mk]["mean"])

        merged_rows.append(merged)

    if not merged_rows:
        raise ValueError("No rows in XRD CSV matched states or loads in benchmark_report")

    all_fieldnames: list[str] = []
    for row_d in merged_rows:
        for k in row_d:
            if k not in all_fieldnames:
                all_fieldnames.append(k)

    merged_csv = out_dir / "xrd_microstructure_merged.csv"
    with merged_csv.open("w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=all_fieldnames)
        writer.writeheader()
        writer.writerows(merged_rows)

    def _ols_residual(vec: np.ndarray, cov: np.ndarray) -> np.ndarray:
        if np.std(cov) < 1e-12:
            return vec - np.mean(vec)
        slope, inter = np.polyfit(cov, vec, 1)
        return vec - (slope * cov + inter)

    correlations: dict[str, dict[str, dict[str, float]]] = {}
    for xc in xrd_cols:
        x_vals = np.asarray([float(r.get(f"xrd_{xc}", float("nan"))) for r in merged_rows], dtype=np.float64)
        correlations[xc] = {}
        for prefix in ("real", "pred"):
            sf_col = f"{prefix}_solid_fraction"
            sf_vals = (
                np.asarray([float(r.get(sf_col, float("nan"))) for r in merged_rows], dtype=np.float64)
                if sf_col in all_fieldnames
                else np.full_like(x_vals, float("nan"))
            )
            for mk in micro_keys:
                col_key = f"{prefix}_{mk}"
                if col_key not in all_fieldnames:
                    continue
                y_vals = np.asarray([float(r.get(col_key, float("nan"))) for r in merged_rows], dtype=np.float64)
                mask = np.isfinite(x_vals) & np.isfinite(y_vals)
                if int(mask.sum()) >= 3 and np.std(x_vals[mask]) > 1e-12 and np.std(y_vals[mask]) > 1e-12:
                    pr, pp = pearsonr(x_vals[mask], y_vals[mask])
                    sr, sp = spearmanr(x_vals[mask], y_vals[mask])
                    slope, intercept = np.polyfit(x_vals[mask], y_vals[mask], 1)

                    part_r = float("nan")
                    part_p = float("nan")
                    pmask = mask & np.isfinite(sf_vals)
                    if mk != "solid_fraction" and int(pmask.sum()) >= 4 and np.std(sf_vals[pmask]) > 1e-12:
                        rx = _ols_residual(x_vals[pmask], sf_vals[pmask])
                        ry = _ols_residual(y_vals[pmask], sf_vals[pmask])
                        if np.std(rx) > 1e-12 and np.std(ry) > 1e-12:
                            pr_c, pp_c = pearsonr(rx, ry)
                            part_r, part_p = float(pr_c), float(pp_c)
                        else:
                            part_r, part_p = 0.0, 1.0

                    correlations[xc][col_key] = {
                        "n": int(mask.sum()),
                        "pearson_r": float(pr),
                        "pearson_p": float(pp),
                        "spearman_rho": float(sr),
                        "spearman_p": float(sp),
                        "partial_pearson_r_given_sf": part_r,
                        "partial_pearson_p_given_sf": part_p,
                        "linear_slope": float(slope),
                        "linear_intercept": float(intercept),
                    }

    summary_json = out_dir / "xrd_microstructure_correlation.json"
    summary_payload = {
        "num_matched_states": len(merged_rows),
        "xrd_columns": xrd_cols,
        "merged_csv": str(merged_csv),
        "correlations": correlations,
    }
    summary_json.write_text(json.dumps(summary_payload, indent=2))

    # Plot primary XRD observable against EASA, TPB density, tortuosity, and compressive pinch-points
    if xrd_cols:
        primary_xrd = xrd_cols[0]
        candidate_targets = [
            ("ssa_pore_coating", "Active Coating EASA (1/µm)"),
            ("tpb_density", "Triple-Phase Boundary (1/µm²)"),
            ("geodesic_tortuosity_z", "Through-Plane Tortuosity τ_Z"),
            ("coating_pinch_fraction", "Pinched Coating Fraction"),
        ]
        plot_targets = [
            (mk, lbl) for mk, lbl in candidate_targets if f"real_{mk}" in all_fieldnames
        ]
        if plot_targets:
            fig, axes = plt.subplots(1, len(plot_targets), figsize=(4.2 * len(plot_targets), 4.0), squeeze=False)
            xv = np.asarray([float(r.get(f"xrd_{primary_xrd}", float("nan"))) for r in merged_rows], dtype=np.float64)
            for ax, (mk, label) in zip(axes[0], plot_targets):
                ry = np.asarray([float(r.get(f"real_{mk}", float("nan"))) for r in merged_rows], dtype=np.float64)
                ax.scatter(xv, ry, color="black", s=42, label="Real XCT")
                if f"pred_{mk}" in all_fieldnames:
                    py = np.asarray([float(r.get(f"pred_{mk}", float("nan"))) for r in merged_rows], dtype=np.float64)
                    ax.scatter(xv, py, color="tab:blue", marker="^", s=46, label="PorousDiff")
                ax.set_xlabel(f"DIAD XRD: {primary_xrd}")
                ax.set_ylabel(label)
                ax.grid(True, alpha=0.3)
                ax.legend(fontsize=8)
            fig.suptitle("DLS K11 DIAD Co-Registered XRD vs. 3D Microstructure & Pinch-Points", fontsize=12)
            fig.tight_layout()
            fig.savefig(out_dir / "diad_xrd_microstructure_correlation.png", dpi=220, bbox_inches="tight")
            plt.close(fig)

    return summary_payload
