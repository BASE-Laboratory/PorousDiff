"""OpenImpala continuum-transport config/result integration & DLS K11 DIAD XRD correlation."""

from __future__ import annotations

import csv
import json
import re
from pathlib import Path
from typing import Iterable, Mapping

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
from scipy.stats import pearsonr, spearmanr


def write_openimpala_ini(
    ini_path: Path,
    tiff_path: Path,
    output_prefix: Path,
    transport_phase: str = "pore",
    phase_value: int = 0,
    directions: tuple[str, ...] = ("z", "x", "y"),
) -> Path:
    """Write a standard OpenImpala `TortuosityFD` INI configuration file for one 3D `.tif` stack."""
    ini_path.parent.mkdir(parents=True, exist_ok=True)
    output_prefix.parent.mkdir(parents=True, exist_ok=True)
    dirs_str = ",".join(directions)
    content = "\n".join(
        [
            "# Auto-generated by PorousDiff v0.3 for OpenImpala TortuosityFD",
            "[Geometry]",
            f"filename = {tiff_path.resolve()}",
            f"phase = {int(phase_value)}",
            f"label = {transport_phase}",
            "",
            "[Solver]",
            "solver_type = DiffusionFD",
            f"directions = {dirs_str}",
            "tolerance = 1e-6",
            "max_iterations = 20000",
            "",
            "[Output]",
            f"output_prefix = {output_prefix.resolve()}",
            "write_json = true",
            "",
        ]
    )
    ini_path.write_text(content)
    return ini_path


def generate_openimpala_job_suite(
    tiff_entries: Iterable[Mapping[str, object]],
    suite_dir: Path,
    openimpala_cmd: str = "openimpala",
) -> dict[str, object]:
    """Generate INI configs, `openimpala_jobs.json`, and `run_openimpala_batch.sh` across methods.

    Each item in `tiff_entries` should contain:
      - `method`: e.g. `"real"`, `"affine_z_squash"`, `"pillar_pore_deletion"`, `"porousdiff"`
      - `state`: state identifier
      - `material`: material key
      - `beamline`: beamline identifier
      - `load_value`: scalar load or stress
      - `tiff_path`: `Path` to exported 3D multi-page `.tif` (`0=pore`, `1=carbon`, `2=coating`)
      - `num_phases`: `2` or `3`
    """
    suite_dir.mkdir(parents=True, exist_ok=True)
    cfg_dir = suite_dir / "configs"
    out_dir = suite_dir / "outputs"
    cfg_dir.mkdir(parents=True, exist_ok=True)
    out_dir.mkdir(parents=True, exist_ok=True)

    jobs: list[dict[str, object]] = []
    shell_lines = [
        "#!/bin/bash",
        "set -euo pipefail",
        f'OPENIMPALA_BIN="${{OPENIMPALA_BIN:-{openimpala_cmd}}}"',
        "",
    ]

    for entry in tiff_entries:
        method = str(entry["method"])
        state = str(entry["state"])
        material = str(entry.get("material", "virgin_carbon"))
        beamline = str(entry.get("beamline", "primary"))
        load_val = float(entry.get("load_value", 0.0))  # type: ignore[arg-type]
        tiff_path = Path(str(entry["tiff_path"]))
        n_ph = int(entry.get("num_phases", 2))  # type: ignore[arg-type]
        stem = tiff_path.stem

        # Always configure ionic pore-phase diffusion (phase 0); for 3-phase also active coating (phase 2)
        # and carbon scaffold (phase 1), for 2-phase solid electronic conduction (phase 1).
        phase_targets = [("pore_ionic", 0), ("carbon_electronic", 1)]
        if n_ph == 3:
            phase_targets.append(("coating_active", 2))

        for transport_name, ph_val in phase_targets:
            job_id = f"{method}__{state}__{stem}__{transport_name}"
            ini_path = cfg_dir / f"{job_id}.ini"
            out_prefix = out_dir / job_id
            write_openimpala_ini(
                ini_path=ini_path,
                tiff_path=tiff_path,
                output_prefix=out_prefix,
                transport_phase=transport_name,
                phase_value=ph_val,
            )
            jobs.append(
                {
                    "job_id": job_id,
                    "method": method,
                    "state": state,
                    "material": material,
                    "beamline": beamline,
                    "load_value": load_val,
                    "transport_phase": transport_name,
                    "phase_value": ph_val,
                    "tiff_path": str(tiff_path.resolve()),
                    "ini_path": str(ini_path.resolve()),
                    "output_json": str((out_dir / f"{job_id}.json").resolve()),
                }
            )
            shell_lines.append(f'"$OPENIMPALA_BIN" "{ini_path.resolve()}"')

    manifest = {"num_jobs": len(jobs), "jobs": jobs}
    manifest_path = suite_dir / "openimpala_jobs.json"
    manifest_path.write_text(json.dumps(manifest, indent=2))

    script_path = suite_dir / "run_openimpala_batch.sh"
    script_path.write_text("\n".join(shell_lines) + "\n")
    script_path.chmod(0o755)
    return {
        "suite_dir": str(suite_dir),
        "manifest_path": str(manifest_path),
        "script_path": str(script_path),
        "num_jobs": len(jobs),
    }


def _parse_single_openimpala_file(path: Path) -> dict[str, float]:
    """Extract `d_eff_x/y/z`, `tau_x/y/z`, and `volume_fraction` from JSON or key-value log."""
    if path.suffix.lower() == ".json":
        raw = json.loads(path.read_text())
        out: dict[str, float] = {}
        for k, v in raw.items():
            if isinstance(v, (int, float)):
                out[k.lower()] = float(v)
            elif isinstance(v, dict):
                for sk, sv in v.items():
                    if isinstance(sv, (int, float)):
                        out[f"{k.lower()}_{sk.lower()}"] = float(sv)
        return out

    text = path.read_text(errors="replace")
    parsed: dict[str, float] = {}
    for m in re.finditer(
        r"(d_eff_[xyz]|deff_[xyz]|tortuosity_[xyz]|tau_[xyz]|volume_fraction|porosity)\s*[:=]\s*([0-9.eE+-]+)",
        text,
        flags=re.IGNORECASE,
    ):
        key = m.group(1).lower().replace("deff_", "d_eff_").replace("tortuosity_", "tau_")
        parsed[key] = float(m.group(2))
    return parsed


def parse_openimpala_results(
    suite_dir: Path,
    out_csv: Path | None = None,
) -> list[dict[str, object]]:
    """Ingest completed OpenImpala outputs matched against `openimpala_jobs.json`."""
    jobs_file = suite_dir / "openimpala_jobs.json"
    if not jobs_file.is_file():
        raise FileNotFoundError(f"Missing OpenImpala job manifest: {jobs_file}")

    jobs = json.loads(jobs_file.read_text()).get("jobs", [])
    rows: list[dict[str, object]] = []
    outputs_dir = suite_dir / "outputs"

    for job in jobs:
        job_id = str(job["job_id"])
        candidates = [
            Path(str(job["output_json"])),
            outputs_dir / f"{job_id}.log",
            outputs_dir / f"{job_id}.txt",
        ]
        found = next((p for p in candidates if p.is_file()), None)
        if found is None:
            continue
        metrics = _parse_single_openimpala_file(found)
        row: dict[str, object] = {
            "job_id": job_id,
            "method": job["method"],
            "state": job["state"],
            "material": job["material"],
            "beamline": job["beamline"],
            "load_value": job["load_value"],
            "transport_phase": job["transport_phase"],
        }
        row.update(metrics)
        rows.append(row)

    if out_csv is not None and rows:
        out_csv.parent.mkdir(parents=True, exist_ok=True)
        keys: list[str] = []
        for r in rows:
            for k in r:
                if k not in keys:
                    keys.append(k)
        with out_csv.open("w", newline="") as f:
            writer = csv.DictWriter(f, fieldnames=keys)
            writer.writeheader()
            writer.writerows(rows)
    return rows


def correlate_xrd_with_microstructure(
    xrd_csv_path: Path,
    benchmark_report: Mapping[str, object],
    out_dir: Path,
    preferred_method: str | None = None,
) -> dict[str, object]:
    """Correlate DLS K11 DIAD co-registered XRD observables with 3D XCT & PorousDiff metrics.

    Expects `xrd_csv_path` to contain a `state` column (matching manifest state names) OR
    (`material` + `load_value`/`stress_kpa`/`load_mv_per_v`), plus one or more numeric XRD
    columns (e.g. `d_spacing_A`, `lattice_strain_pct`, `fwhm_deg`, `coating_peak_ratio`).
    """
    out_dir.mkdir(parents=True, exist_ok=True)
    with xrd_csv_path.open("r", newline="") as f:
        xrd_rows = list(csv.DictReader(f))
    if not xrd_rows:
        raise ValueError(f"XRD CSV {xrd_csv_path} is empty")

    reserved = {
        "state",
        "folder",
        "dataset",
        "material",
        "beamline",
        "load",
        "load_value",
        "stress_kpa",
        "load_mv_per_v",
    }
    xrd_cols = [
        c
        for c in (xrd_rows[0].keys() if xrd_rows else [])
        if c and c.strip().lower() not in reserved
    ]

    micro_keys = [
        "solid_fraction",
        "coating_fraction",
        "ssa_pore_coating",
        "tpb_density",
        "wired_coating_fraction",
        "geodesic_tortuosity_z",
    ]

    merged_rows: list[dict[str, object]] = []
    for xrow in xrd_rows:
        st_match: str | None = None
        raw_st = (xrow.get("state") or xrow.get("folder") or xrow.get("dataset") or "").strip()
        if raw_st and raw_st in benchmark_report:
            st_match = raw_st
        elif raw_st:
            # Allow suffix match when collision-safe prefixes like `DLS_K11_DIAD__...` were added
            for cand_st in benchmark_report:
                if str(cand_st).endswith(raw_st):
                    st_match = str(cand_st)
                    break

        if st_match is None:
            raw_lv = xrow.get("load_value") or xrow.get("stress_kpa") or xrow.get("load_mv_per_v") or xrow.get("load")
            raw_mat = (xrow.get("material") or "").strip()
            if raw_lv is not None and str(raw_lv).strip():
                target_lv = float(str(raw_lv).strip())
                best_st = None
                best_diff = float("inf")
                for cand_st, entry in benchmark_report.items():
                    ent = entry  # type: ignore[assignment]
                    if raw_mat and str(ent.get("material", "")) != raw_mat:  # type: ignore[union-attr]
                        continue
                    diff = abs(float(ent.get("load_value", 0.0)) - target_lv)  # type: ignore[union-attr]
                    if diff < best_diff and diff <= max(1e-4, 0.05 * max(abs(target_lv), 1e-3)):
                        best_diff = diff
                        best_st = str(cand_st)
                st_match = best_st

        if st_match is None:
            continue

        entry = benchmark_report[st_match]  # type: ignore[index]
        methods_dict = entry.get("methods", {})  # type: ignore[union-attr]
        chosen_method = preferred_method
        if chosen_method is None or chosen_method not in methods_dict:
            non_base = [m for m in methods_dict if m not in ("affine_z_squash", "pillar_pore_deletion")]
            chosen_method = non_base[0] if non_base else (next(iter(methods_dict), None))

        merged: dict[str, object] = {
            "state": st_match,
            "material": entry.get("material", ""),  # type: ignore[union-attr]
            "load_value": float(entry.get("load_value", 0.0)),  # type: ignore[union-attr]
            "pred_method": chosen_method or "",
        }
        for xc in xrd_cols:
            try:
                merged[f"xrd_{xc}"] = float(str(xrow[xc]).strip())
            except (TypeError, ValueError):
                merged[f"xrd_{xc}"] = float("nan")

        real_m = entry["real"]["metrics"]  # type: ignore[index]
        for mk in micro_keys:
            merged[f"real_{mk}"] = float(real_m[mk]["mean"])

        if chosen_method and chosen_method in methods_dict:
            pred_m = methods_dict[chosen_method]["metrics"]
            for mk in micro_keys:
                merged[f"pred_{mk}"] = float(pred_m[mk]["mean"])

        merged_rows.append(merged)

    if not merged_rows:
        raise ValueError("No rows in XRD CSV matched states or loads in benchmark_report")

    merged_csv = out_dir / "xrd_microstructure_merged.csv"
    with merged_csv.open("w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=list(merged_rows[0].keys()))
        writer.writeheader()
        writer.writerows(merged_rows)

    correlations: dict[str, dict[str, dict[str, float]]] = {}
    for xc in xrd_cols:
        x_vals = np.asarray([float(r[f"xrd_{xc}"]) for r in merged_rows], dtype=np.float64)
        correlations[xc] = {}
        for prefix in ("real", "pred"):
            for mk in micro_keys:
                col_key = f"{prefix}_{mk}"
                if col_key not in merged_rows[0]:
                    continue
                y_vals = np.asarray([float(r[col_key]) for r in merged_rows], dtype=np.float64)
                mask = np.isfinite(x_vals) & np.isfinite(y_vals)
                if int(mask.sum()) >= 3 and np.std(x_vals[mask]) > 1e-12 and np.std(y_vals[mask]) > 1e-12:
                    pr, pp = pearsonr(x_vals[mask], y_vals[mask])
                    sr, sp = spearmanr(x_vals[mask], y_vals[mask])
                    slope, intercept = np.polyfit(x_vals[mask], y_vals[mask], 1)
                    correlations[xc][col_key] = {
                        "n": int(mask.sum()),
                        "pearson_r": float(pr),
                        "pearson_p": float(pp),
                        "spearman_rho": float(sr),
                        "spearman_p": float(sp),
                        "linear_slope": float(slope),
                        "linear_intercept": float(intercept),
                    }

    summary_json = out_dir / "xrd_microstructure_correlation.json"
    summary_payload = {
        "num_matched_states": len(merged_rows),
        "xrd_columns": xrd_cols,
        "merged_csv": str(merged_csv),
        "correlations": correlations,
    }
    summary_json.write_text(json.dumps(summary_payload, indent=2))

    # Plot primary XRD observable against EASA, TPB density, and through-plane tortuosity
    if xrd_cols:
        primary_xrd = xrd_cols[0]
        fig, axes = plt.subplots(1, 3, figsize=(13.5, 4.0))
        plot_targets = [
            ("ssa_pore_coating", "Active Coating EASA (1/µm)"),
            ("tpb_density", "Triple-Phase Boundary (1/µm²)"),
            ("geodesic_tortuosity_z", "Through-Plane Tortuosity τ_Z"),
        ]
        xv = np.asarray([float(r[f"xrd_{primary_xrd}"]) for r in merged_rows], dtype=np.float64)
        for ax, (mk, label) in zip(axes, plot_targets):
            ry = np.asarray([float(r[f"real_{mk}"]) for r in merged_rows], dtype=np.float64)
            ax.scatter(xv, ry, color="black", s=42, label="Real XCT")
            if f"pred_{mk}" in merged_rows[0]:
                py = np.asarray([float(r[f"pred_{mk}"]) for r in merged_rows], dtype=np.float64)
                ax.scatter(xv, py, color="tab:blue", marker="^", s=46, label="PorousDiff")
            ax.set_xlabel(f"DIAD XRD: {primary_xrd}")
            ax.set_ylabel(label)
            ax.grid(True, alpha=0.3)
            ax.legend(fontsize=8)
        fig.suptitle("DLS K11 DIAD Co-Registered XRD vs. 3D Microstructural Electrochemistry", fontsize=12)
        fig.tight_layout()
        fig.savefig(out_dir / "diad_xrd_microstructure_correlation.png", dpi=220, bbox_inches="tight")
        plt.close(fig)

    return summary_payload
